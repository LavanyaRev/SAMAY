interface UndertakingsDocumentsStore {
  conditions: UndertakingConditionItem[];
  documents: TrackedDocumentItem[];
  dedupKeys: Set<string>;
}

const memoryStore: UndertakingsDocumentsStore = {
  conditions: JSON.parse(JSON.stringify(INITIAL_CONDITIONS)),
  documents: JSON.parse(JSON.stringify(INITIAL_DOCUMENTS)),
  dedupKeys: new Set(
    INITIAL_DOCUMENTS.map((d) => `${d.institutionId}::${d.type}::${d.reference}`),
  ),
};

const listeners = new Set<() => void>();
function emitChange() {
  for (const fn of listeners) fn();
}

export function subscribeUndertakingsDocumentsStore(
  listener: () => void,
): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function getUndertakingsDocumentsSnapshot(): UndertakingsDocumentsStore {
  return memoryStore;
}

export function recordOfficerConditionInStore(input: {
  applicationRef: string;
  institutionName: string;
  region: string;
  conditionType: string;
  description: string;
  requiredEvidenceTypes: string[];
  dueDate: string;
}): UndertakingConditionItem {
  const created: UndertakingConditionItem = {
    id: `cond-${memoryStore.conditions.length + 1}`,
    undertakingId: "und-custom",
    applicationRef: input.applicationRef,
    institutionId: "inst-custom",
    institutionName: input.institutionName,
    region: input.region,
    conditionType: input.conditionType,
    description: input.description,
    requiredEvidenceTypes: input.requiredEvidenceTypes,
    dueDate: input.dueDate,
    slaState: "ON_TRACK",
    status: "PENDING",
    escalationLevel: 0,
    waivedByRole: null,
    waiverReason: null,
    submissions: [],
    extractionResult: null,
  };
  memoryStore.conditions = [created, ...memoryStore.conditions];
  emitChange();
  return created;
}

export function submitEvidenceForConditionInStore(
  conditionId: string,
  input: {
    providedEvidenceTypes: string[];
    remarks: string;
  },
): UndertakingConditionItem | null {
  const cond = memoryStore.conditions.find((c) => c.id === conditionId);
  if (!cond) return null;
  const missing = cond.requiredEvidenceTypes.filter(
    (req) => !input.providedEvidenceTypes.includes(req),
  );
  cond.submissions.push({
    id: `sub-${cond.id}-${cond.submissions.length + 1}`,
    attemptNumber: cond.submissions.length + 1,
    submittedByRole: "INSTITUTION",
    providedEvidenceTypes: input.providedEvidenceTypes,
    remarks: input.remarks,
    status: "SUBMITTED",
    missingEvidenceTypes: missing,
    reviewReason: null,
    submittedAt: "2026-05-15 12:00 IST",
  });
  cond.status = "SUBMITTED";
  cond.slaState = "PAUSED";
  emitChange();
  return cond;
}

export function reviewConditionInStore(
  conditionId: string,
  input: {
    decision: "ACCEPT" | "REJECT" | "REQUEST_MORE";
    actorRole: string;
    reason?: string;
  },
): UndertakingConditionItem {
  if (input.actorRole === "INSTITUTION") {
    throw new Error(
      "Statutory violation: Institutions cannot verify their own undertaking evidence.",
    );
  }
  const cond = memoryStore.conditions.find((c) => c.id === conditionId);
  if (!cond) throw new Error(`Condition ${conditionId} not found`);

  const latest = cond.submissions[cond.submissions.length - 1];
  if (latest) {
    latest.reviewReason = input.reason || "Verified compliant";
    latest.status =
      input.decision === "ACCEPT"
        ? "VERIFIED"
        : input.decision === "REJECT"
          ? "REJECTED"
          : "MORE_INFO_REQUESTED";
  }

  if (input.decision === "ACCEPT") {
    cond.status = "VERIFIED";
    cond.slaState = "ON_TRACK";
  } else if (input.decision === "REJECT") {
    cond.status = "REJECTED";
    cond.slaState = "DUE_SOON";
  } else {
    cond.status = "PENDING";
    cond.slaState = "DUE_SOON";
  }
  emitChange();
  return cond;
}

export function waiveConditionInStore(
  conditionId: string,
  input: {
    actorRole: string;
    waiverReason: string;
  },
): UndertakingConditionItem {
  if (input.actorRole !== "BUREAU_OFFICER" && input.actorRole !== "ADMIN") {
    throw new Error(
      "Waiving a condition is reserved strictly for the Competent Authority (BUREAU_OFFICER / ADMIN).",
    );
  }
  const cond = memoryStore.conditions.find((c) => c.id === conditionId);
  if (!cond) throw new Error(`Condition ${conditionId} not found`);
  cond.status = "WAIVED_BY_AUTHORITY";
  cond.waivedByRole = input.actorRole;
  cond.waiverReason = input.waiverReason;
  cond.slaState = "ON_TRACK";
  emitChange();
  return cond;
}

export function submitRenewalInStore(
  documentId: string,
  input: {
    newReference: string;
    newValidFrom: string;
    newExpiryDate: string;
    remarks: string;
  },
): TrackedDocumentItem | null {
  const doc = memoryStore.documents.find((d) => d.id === documentId);
  if (!doc) return null;
  doc.pendingRenewal = {
    ...input,
    submittedAt: "2026-05-15 14:00 IST",
  };
  doc.status = "RENEWAL_SUBMITTED";
  emitChange();
  return doc;
}

export function verifyRenewalInStore(
  documentId: string,
  input: {
    decision: "ACCEPT" | "REJECT";
    actorRole: string;
    reason?: string;
  },
): TrackedDocumentItem {
  if (input.actorRole === "INSTITUTION") {
    throw new Error(
      "Statutory violation: Institutions cannot verify their own document renewals.",
    );
  }
  const doc = memoryStore.documents.find((d) => d.id === documentId);
  if (!doc || !doc.pendingRenewal) {
    throw new Error(`Document ${documentId} has no pending renewal`);
  }

  if (input.decision === "REJECT") {
    doc.status = "RENEWAL_REJECTED";
    emitChange();
    return doc;
  }

  doc.versionHistory.push({
    versionNumber: doc.version,
    reference: doc.reference,
    validFrom: doc.validFrom,
    expiryDate: doc.expiryDate,
    archivedAt: "2026-05-15",
  });
  doc.version += 1;
  doc.reference = doc.pendingRenewal.newReference;
  doc.validFrom = doc.pendingRenewal.newValidFrom;
  doc.expiryDate = doc.pendingRenewal.newExpiryDate;
  doc.daysRemaining = 365;
  doc.pendingRenewal = null;
  doc.status = "RENEWAL_VERIFIED";
  emitChange();
  return doc;
}

export function importCsvDocumentsInStore(
  csvText: string,
  dryRun: boolean,
): CsvImportPreviewReport {
  const lines = csvText
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l.length > 0);
  const hasHeader =
    lines.length > 0 && lines[0].toLowerCase().includes("institution_id");
  const dataLines = hasHeader ? lines.slice(1) : lines;

  const rowErrors: CsvImportPreviewReport["rowErrors"] = [];
  let validRowsCount = 0;
  let createdCount = 0;
  let skippedIdempotentCount = 0;
  const validTypes = new Set(["LEASE", "LAND_DOCUMENT", "OTHER"]);

  dataLines.forEach((line, idx) => {
    const rowNumber = hasHeader ? idx + 2 : idx + 1;
    const cols = line.split(",").map((c) => c.trim());
    const errors: string[] = [];

    if (cols.length < 7) {
      errors.push("Expected 7 columns.");
    } else {
      const [
        institutionId,
        institutionName,
        region,
        type,
        reference,
        validFrom,
        expiryDate,
      ] = cols;
      if (!validTypes.has(type)) {
        errors.push(`Invalid type "${type}" (expected LEASE, LAND_DOCUMENT, OTHER).`);
      }
      if (!reference) errors.push("reference is required.");
      if (expiryDate <= validFrom) {
        errors.push("expiry_date must be after valid_from.");
      }

      if (errors.length === 0) {
        validRowsCount++;
        const dedupKey = `${institutionId}::${type}::${reference}`;
        if (memoryStore.dedupKeys.has(dedupKey)) {
          skippedIdempotentCount++;
        } else if (!dryRun) {
          memoryStore.dedupKeys.add(dedupKey);
          memoryStore.documents.unshift({
            id: `doc-csv-${memoryStore.documents.length + 1}`,
            institutionId,
            institutionName,
            region,
            type,
            reference,
            validFrom,
            expiryDate,
            daysRemaining: 45,
            version: 1,
            versionHistory: [],
            status: "EXPIRING_SOON",
            pendingRenewal: null,
            extractionResult: null,
          });
          createdCount++;
        }
      }
    }

    if (errors.length > 0) {
      rowErrors.push({ rowNumber, rawLine: line, errors });
    }
  });

  if (!dryRun) emitChange();

  return {
    dryRun,
    totalRows: dataLines.length,
    validRowsCount,
    errorRowsCount: rowErrors.length,
    createdCount,
    skippedIdempotentCount,
    rowErrors,
  };
}

