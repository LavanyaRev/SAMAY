import type { ExtractionResultPayload } from "@/components/ui/confidence-badge";

export type ConditionStatus =
  | "PENDING"
  | "SUBMITTED"
  | "UNDER_VERIFICATION"
  | "VERIFIED"
  | "REJECTED"
  | "OVERDUE"
  | "WAIVED_BY_AUTHORITY";

export type TrackedDocStatus =
  | "VALID"
  | "EXPIRING_SOON"
  | "EXPIRED"
  | "RENEWAL_SUBMITTED"
  | "RENEWAL_VERIFIED"
  | "RENEWAL_REJECTED";

export interface ConditionSubmissionEntry {
  id: string;
  attemptNumber: number;
  submittedByRole: string;
  providedEvidenceTypes: string[];
  remarks: string;
  status: "SUBMITTED" | "VERIFIED" | "REJECTED" | "MORE_INFO_REQUESTED";
  missingEvidenceTypes: string[];
  reviewReason: string | null;
  submittedAt: string;
}

export interface UndertakingConditionItem {
  id: string;
  undertakingId: string;
  applicationRef: string;
  institutionId: string;
  institutionName: string;
  region: string;
  conditionType: string;
  description: string;
  requiredEvidenceTypes: string[];
  dueDate: string;
  slaState: "ON_TRACK" | "DUE_SOON" | "OVERDUE" | "PAUSED";
  status: ConditionStatus;
  escalationLevel: 0 | 1 | 2 | 3;
  waivedByRole: string | null;
  waiverReason: string | null;
  submissions: ConditionSubmissionEntry[];
  extractionResult?: ExtractionResultPayload | null;
}

export interface TrackedDocumentItem {
  id: string;
  institutionId: string;
  institutionName: string;
  region: string;
  type: "LEASE" | "LAND_DOCUMENT" | "OTHER" | string;
  reference: string;
  validFrom: string;
  expiryDate: string;
  daysRemaining: number;
  version: number;
  versionHistory: Array<{
    versionNumber: number;
    reference: string;
    validFrom: string;
    expiryDate: string;
    archivedAt: string;
  }>;
  status: TrackedDocStatus;
  pendingRenewal: {
    newReference: string;
    newValidFrom: string;
    newExpiryDate: string;
    remarks: string;
    submittedAt: string;
  } | null;
  extractionResult: ExtractionResultPayload | null;
}

export interface CsvImportPreviewReport {
  dryRun: boolean;
  totalRows: number;
  validRowsCount: number;
  errorRowsCount: number;
  createdCount: number;
  skippedIdempotentCount: number;
  rowErrors: Array<{
    rowNumber: number;
    rawLine: string;
    errors: string[];
  }>;
}

